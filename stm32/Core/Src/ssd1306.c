/**
  * @brief  Initialize the SSD1306 display (command sequence + clear).
  * @param  hi2c: pointer to the I2C handle (e.g. &hi2c1)
  * @retval None
  */
void ssd1306_init(I2C_HandleTypeDef* hi2c)
{
  hi2c_ = hi2c;

  uint8_t cmds[] = {
    0x00,       /* command stream */
    0xAE,       /* display off */
    0xD5, 0x80, /* clock div */
    0xA8, 0x3F, /* multiplex 64 */
    0xD3, 0x00, /* display offset */
    0x40,       /* start line */
    0x8D, 0x14, /* charge pump */
    0x20, 0x00, /* horizontal addressing */
    0xA1,       /* segment remap */
    0xC8,       /* COM scan direction */
    0xDA, 0x12, /* COM pins */
    0x81, 0xCF, /* contrast */
    0xD9, 0xF1, /* pre-charge */
    0xDB, 0x40, /* VCOM detect */
    0xA4,       /* display on resume */
    0xA6,       /* normal display */
    0xAF        /* display on */
  };

  HAL_I2C_Master_Transmit(hi2c_, SSD1306_I2C_ADDR, cmds, sizeof(cmds), 100);
  ssd1306_clear();
  ssd1306_flush();
}

/**
  * @brief  Clear the framebuffer (does not touch the display until flush).
  * @retval None
  */
void ssd1306_clear(void)
{
  memset(buffer_, 0, sizeof(buffer_));
}

/**
  * @brief  Set the internal cursor position (used by future draw calls).
  * @param  x: column in pixels (0-127)
  * @param  y: page row (0-7)
  * @retval None
  */
void ssd1306_set_cursor(uint8_t x, uint8_t y)
{
  cursor_x_ = x;
  cursor_y_ = y;
}

/**
  * @brief  Draw a single character into the framebuffer.
  * @param  x_col: left column in pixels (0-122)
  * @param  y_page: page row (0-7)
  * @param  c: ASCII character (0x20-0x7E, others render as space)
  * @retval None
  */
void ssd1306_draw_char(uint8_t x_col, uint8_t y_page, char c)
{
  if (x_col > SSD1306_MAX_COL || y_page >= SSD1306_PAGES)
  {
    return;
  }

  if (c < 0x20 || c > 0x7E)
  {
    c = ' ';
  }

  const uint8_t* glyph = font_6x8[c - 0x20];
  uint8_t* dst = &buffer_[y_page * SSD1306_WIDTH + x_col];

  for (uint8_t i = 0; i < SSD1306_FONT_W; i++)
  {
    dst[i] = glyph[i];
  }
}

/**
  * @brief  Draw a null-terminated string into the framebuffer.
  * @param  x_col: left column in pixels (0-122)
  * @param  y_page: page row (0-7)
  * @param  str: null-terminated string
  * @retval None
  */
void ssd1306_draw_string(uint8_t x_col, uint8_t y_page, const char* str)
{
  while (*str != '\0')
  {
    ssd1306_draw_char(x_col, y_page, *str);
    x_col += SSD1306_FONT_W;
    if (x_col > SSD1306_MAX_COL)
    {
      break;  /* right edge reached, stop */
    }
    str++;
  }
}

/**
  * @brief  Send the framebuffer to the display, page by page.
  * @retval None
  */
void ssd1306_flush(void)
{
  for (uint8_t page = 0; page < SSD1306_PAGES; page++)
  {
    uint8_t page_cmd[] = {0x00, (uint8_t)(0xB0 + page), 0x00, 0x10};
    HAL_I2C_Master_Transmit(hi2c_, SSD1306_I2C_ADDR, page_cmd, sizeof(page_cmd), 10);

    uint8_t data[SSD1306_WIDTH + 1];
    data[0] = 0x40;  /* data stream */
    memcpy(data + 1, &buffer_[page * SSD1306_WIDTH], SSD1306_WIDTH);
    HAL_I2C_Master_Transmit(hi2c_, SSD1306_I2C_ADDR, data, SSD1306_WIDTH + 1, 100);
  }
}

